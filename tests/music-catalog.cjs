const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const compiled = ts.transpileModule(fs.readFileSync(path.join(root,'src/music-catalog.ts'),'utf8'), {
  compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}
}).outputText;
const loaded = {exports:{}};
new Function('exports','module','require',compiled)(loaded.exports,loaded,require);
const {mergePrivateManifest,promoteNewTracks,mergeCachedTracks,preserveTrackIndex,startupTrackIndex,isFolderTrack,retainFolderTracks} = loaded.exports;
const song = id => ({id,title:id,filename:`${id}.mp3`,url:`https://example.test/${id}.mp3`});
const ids = tracks => tracks.map(t=>t.id);
const checks=[];
function pass(name){checks.push(name);console.log('PASS '+name);}
const a=song('a'),b=song('b'),winter=song('winter'),fresh=song('new');
assert.deepEqual(ids(mergePrivateManifest([a,b],[winter])),['a','b','winter']);
assert.equal(mergePrivateManifest([a,{...winter,url:'wrong'}],[winter]).find(t=>t.id==='winter').url,winter.url);
pass('Private song survives a public manifest that omits or duplicates its ID');
const ordered=promoteNewTracks([fresh,winter,b,a],[winter,a,b]);
assert.deepEqual(ids(ordered),['new','winter','a','b']);
assert.deepEqual(ids(promoteNewTracks([b,a,winter,fresh],ordered)),ids(ordered));
pass('New songs lead and refreshes preserve established order');
const cached=[{...a,url:'C:/music/a.mp3',localPath:'C:/music/a.mp3'}, {...b,url:'C:/music/b.mp3',localPath:'C:/music/b.mp3'}];
const startup=mergeCachedTracks([winter,b,a],cached);
assert.deepEqual(ids(startup),['winter','a','b']);
assert.equal(startup[1].localPath,'C:/music/a.mp3');
assert.equal(preserveTrackIndex(cached,1,startup),2);
pass('Offline cached playlists gain the private song while preserving cached files and selected identity');
assert.equal(ordered[preserveTrackIndex([winter,a,b],1,ordered)].id,'a');
assert.equal(preserveTrackIndex([a],0,[b]),0);
pass('Reordering retains the selected song; removed selections fall back to the first song');
const oldCustom={...a,id:'custom-0-a.mp3',url:'C:/folder/a.mp3'};
assert.equal(preserveTrackIndex([oldCustom],0,[winter,{...oldCustom,id:'custom:c:/folder/a.mp3'}]),1);
pass('Folder ID migration keeps the selected audio file');
const local={...song('custom:c:/folder/local.mp3'),url:'C:/folder/local.mp3'};
const withFolder=promoteNewTracks(retainFolderTracks([fresh,winter,a],[winter,local,a],true),[winter,local,a]);
assert.deepEqual(ids(withFolder),['new','winter',local.id,'a']);
assert.equal(withFolder[preserveTrackIndex([winter,local,a],1,withFolder)].url,local.url);
assert.deepEqual(ids(retainFolderTracks([winter],[local],false)),['winter']);
assert.deepEqual(ids([oldCustom,local,winter].filter(t=>!isFolderTrack(t))),['winter']);
pass('Automatic catalog refresh retains selected folder audio and excludes local files from remote downloads');
assert.deepEqual(ids(mergePrivateManifest([null,a,a,{id:'bad'}],[winter])),['a','winter']);
assert.deepEqual(ids(mergeCachedTracks([winter],[null,a,a])),['winter','a']);
pass('Malformed and duplicate catalog rows do not duplicate or crash the playlist');
assert.equal(startupTrackIndex([a,song("gs_christmas_remix_01")]),1);
assert.equal(startupTrackIndex([a]),0);
pass("Startup chooses Christmas even when the saved song was different");
const bundled=JSON.parse(fs.readFileSync(path.join(root,'config/music.json'),'utf8'));
const actual=mergePrivateManifest(bundled,[]).reverse();
assert.equal(actual[0].id,'gs_christmas_remix_01');
assert.equal(actual.length,13);
assert.equal(new Set(actual.map(t=>t.id)).size,13);
pass('The real local catalog has thirteen unique songs with Christmas Remix 01 first');
fs.writeFileSync(path.join(root,'test-results/music-catalog-results.json'),JSON.stringify({status:'passed',checks},null,2));
